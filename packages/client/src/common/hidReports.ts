// Virtual HID side of remote control that does NOT need a driver to be correct: the HID report
// descriptors the virtual keyboard/mouse expose, and the conversion of the wire events (scan-code
// key ids, mouse buttons/position/wheel) into the exact input reports those descriptors describe.
// The (future) Windows service forwards these bytes to the virtual HID driver unchanged — see
// native/virtual-hid/README.md. Pure logic, no imports, so it runs under plain `node`.
//
// Hand-checked against the USB HID Usage Tables: keyboard page 0x07, generic desktop 0x01, button
// page 0x09, consumer page 0x0C (AC Pan, horizontal wheel).

