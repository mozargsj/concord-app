/** Modifier usages 0xE0..0xE7 map to bits 0..7 of the first report byte. */
const isModifier = (usage: number) => usage >= 0xe0 && usage <= 0xe7;

/** Keeps the held-key state of the virtual keyboard and renders it as 8-byte input reports.
 * Combinations are just states (spec 9, 19): Ctrl down, Shift down, Esc down... and Windows reads
 * the combination out of the report stream. More than 6 simultaneous non-modifier keys report
 * rollover-error (0x01 in every slot) exactly like real hardware. */
export class KeyboardReportBuilder {
  private modifiers = 0;
  private keys: number[] = [];

  press(keyId: number): boolean {
    const usage = KEY_ID_TO_USAGE[keyId];
    if (usage === undefined) return false;
    if (isModifier(usage)) this.modifiers |= 1 << (usage - 0xe0);
    else if (!this.keys.includes(usage)) this.keys.push(usage);
    return true;
  }

  release(keyId: number): boolean {
    const usage = KEY_ID_TO_USAGE[keyId];
    if (usage === undefined) return false;
    if (isModifier(usage)) this.modifiers &= ~(1 << (usage - 0xe0));
    else this.keys = this.keys.filter((k) => k !== usage);
    return true;
  }

  /** Input Reset: nothing held. */
  reset(): void {
    this.modifiers = 0;
    this.keys = [];
  }

  report(): Uint8Array {
    const report = new Uint8Array(KEYBOARD_REPORT_LENGTH);
    report[0] = this.modifiers;
    if (this.keys.length > 6) report.fill(0x01, 2);
    else this.keys.forEach((usage, index) => (report[2 + index] = usage));
    return report;
  }
}

/** Same for the virtual absolute mouse. Wheel/pan are one-shot: they appear in the report that
 * carries them and are zero in the next one. */
export class MouseReportBuilder {
  private buttons = 0;
  private x = 0;
  private y = 0;
  private wheel = 0;
  private pan = 0;

  setButton(button: number, down: boolean): boolean {
    // wire ids: 0 left, 1 right, 2 middle, 3 x1, 4 x2 — HID button usages 1..5 in the same order
    if (!Number.isInteger(button) || button < 0 || button > 4) return false;
    if (down) this.buttons |= 1 << button;
    else this.buttons &= ~(1 << button);
    return true;
  }

  moveAbs(x: number, y: number): void {
    const clamp = (v: number) => Math.max(0, Math.min(MOUSE_ABS_MAX, Math.round(v)));
    this.x = clamp(x);
    this.y = clamp(y);
  }

  scroll(vertical: number, horizontal: number): void {
    const clamp = (v: number) => Math.max(-127, Math.min(127, Math.round(v)));
    this.wheel = clamp(vertical);
    this.pan = clamp(horizontal);
  }

  reset(): void {
    this.buttons = 0;
    this.wheel = 0;
    this.pan = 0;
  }

  /** Renders the report and clears the one-shot wheel/pan. */
  report(): Uint8Array {
    const report = new Uint8Array(MOUSE_REPORT_LENGTH);
    report[0] = this.buttons;
    report[1] = this.x & 0xff;
    report[2] = this.x >> 8;
    report[3] = this.y & 0xff;
    report[4] = this.y >> 8;
    report[5] = this.wheel & 0xff; // int8 two's complement
    report[6] = this.pan & 0xff;
    this.wheel = 0;
    this.pan = 0;
    return report;
  }
}
