// Session authority of the remote-control feature (spec sections 12-17, 24, 38). The renderer owns
// the data channels and the UI, but EVERYTHING that decides whether input is allowed lives here:
// presence status, "one control at a time", the refusal cooldown, the session id / sequence
// numbers, permissions, the heartbeat watchdog and Input Reset. A frame arriving from a peer is
// only ever injected if it passes the checks in handleInput/handleMove below.

interface PeerInfo {
  peerId: string;
  userId: string;
  name: string;
}

interface Pending {
  id: string;
  kind: SolicitationKind;
  direction: 'incoming' | 'outgoing';
  peer: PeerInfo;
  perms: RcPermissions;
  /** Session id: generated by the controlled side (offer: before sending, request: on accept). */
  sid: string | null;
  timer: ReturnType<typeof setTimeout>;
}

interface Session {
  sid: string;
  role: 'controller' | 'controlled';
  peer: PeerInfo;
  perms: RcPermissions;
  keyHook: boolean;
  lastFrameAt: number;
  lastSeq: { key: number; btn: number; wheel: number; mv: number };
  watchdog: ReturnType<typeof setInterval> | null;
  clipboardTimer: ReturnType<typeof setInterval> | null;
  lastClipboard: string;
  /** Controller hardware validated against the virtual devices (controlled side); permissive until
   * the controller's `caps` frame arrives. */
  negotiated: NegotiatedCaps;
  capsSeen: boolean;
  hookEvents: number;
  keyFramesIn: number;
  keyDropped: number;
  /** Opt-in input diagnostics: per-event outcomes kept in memory only while this is on. */
  diagOn: boolean;
  diagItems: DiagItem[];
  diagNext: number;
  diagLastMove: number;
  lastSwallow: boolean;
  captureLog: Array<{ at: number; swallowing: boolean; why: string }>;
  hookRearms: number;
}

let mainWindow: BrowserWindow | null = null;
let status: PresenceStatus = 'online';
/** Id of the display currently shared in full (desktopCapturer display_id), null = not sharing a whole screen. */
let shareDisplayId: string | null = null;
let session: Session | null = null;
let pending: Pending | null = null;
let captureActive = false; // controller: the shared-screen view has the keyboard

// ---- refusal cooldown store (persisted, spec 13.2) ------------------------------------------------

type StoredBlock = BlockRecord & { displayName: string };
let blocks: Record<string, StoredBlock> | null = null;
const blocksPath = () => path.join(app.getPath('userData'), 'remote-control-blocks.json');

function loadBlocks(): Record<string, StoredBlock> {
  if (blocks) return blocks;
  try {
    blocks = JSON.parse(readFileSync(blocksPath(), 'utf8')) as Record<string, StoredBlock>;
  } catch {
    blocks = {};
  }
  return blocks;
}

function saveBlocks(): void {
  try {
    writeFileSync(blocksPath(), JSON.stringify(loadBlocks()));
  } catch {
    // best effort — losing the file only means an in-memory-only cooldown until next refusal
  }
}

// ---- helpers -------------------------------------------------------------------------------------

function emit(channel: string, payload?: unknown): void {
  if (mainWindow && !mainWindow.isDestroyed()) mainWindow.webContents.send(channel, payload);
}

export { emit as emitToRenderer };

/** The live session as far as other main-process modules (file transfer) need to know it. */
export function getActiveSession(): { sid: string; peerId: string; perms: RcPermissions } | null {
  return session ? { sid: session.sid, peerId: session.peer.peerId, perms: session.perms } : null;
}

const sessionEndListeners: Array<() => void> = [];
/** Registers cleanup that must run whenever a session ends (open file transfers...). */
export function onSessionEnd(listener: () => void): void {
  sessionEndListeners.push(listener);
}

function isStatus(value: unknown): value is PresenceStatus {
  return value === 'online' || value === 'busy' || value === 'unavailable' || value === 'offline';
}

function isPeer(value: unknown): value is PeerInfo {
  const p = value as PeerInfo;
  return !!p && typeof p.peerId === 'string' && typeof p.userId === 'string' && typeof p.name === 'string';
}

function sessionInfo(s: Session): RcSessionInfo {
  return {
    sid: s.sid,
    role: s.role,
    peerId: s.peer.peerId,
    peerUserId: s.peer.userId,
    peerName: s.peer.name,
    perms: s.perms,
    keyHook: s.keyHook
  };
}

function clearPending(): Pending | null {
  const p = pending;
  if (p) clearTimeout(p.timer);
  pending = null;
  return p;
}

function startPending(
  direction: Pending['direction'],
  kind: SolicitationKind,
  peer: PeerInfo,
  perms: RcPermissions,
  sid: string | null
): Pending {
  const id = randomUUID();
  const timer = setTimeout(() => {
    if (pending?.id !== id) return;
    pending = null;
    emit('rc:pending-expired', { id }); // expiring is never counted as a refusal
  }, RC_TIMING.solicitationTimeoutMs);
  pending = { id, kind, direction, peer, perms, sid, timer };
  return pending;
}

// ---- session lifecycle ---------------------------------------------------------------------------

/** Why keyboard capture is on or off right now (controller). */
function captureWhy(s: Session): string {
  if (s.role !== 'controller') return 'n/a';
  if (!s.perms.keyboard) return 'sem permissão de teclado';
  if (!captureActive) return 'a tela transmitida não está em foco/visível';
  if (!mainWindow?.isFocused()) return 'o Concord perdeu o foco do Windows';
  return 'capturando';
}

/** One hook handler per session, shared by the first start and every re-arm. */
function makeHookHandler(s: Session): Parameters<typeof injector.startKeyHook>[0] {
  return (event) => {
    if (session !== s) return;
    if (event.exitRequested) {
      endSession('user-exit');
      return;
    }
    if (s.role === 'controller' && captureActive) {
      s.hookEvents++;
      emit('rc:hook-key', { keyId: event.keyId, down: event.down });
    }
  };
}

function applySwallow(): void {
  const s = session;
  const shouldSwallow = !!s && s.role === 'controller' && s.perms.keyboard && captureActive && !!mainWindow?.isFocused();
  if (s && shouldSwallow !== s.lastSwallow) {
    s.lastSwallow = shouldSwallow;
    s.captureLog.push({ at: Date.now(), swallowing: shouldSwallow, why: captureWhy(s) });
    if (s.captureLog.length > 20) s.captureLog.shift();
    // Windows silently drops a low-level hook whose callback ever ran too slowly (heavy CPU while
    // capturing the screen and encoding video is exactly that). Re-arming it every time capture
    // starts means a hook that died since the last time can't leave typing broken until the session ends.
    if (shouldSwallow && s.keyHook) {
      injector.stopKeyHook();
      s.keyHook = injector.startKeyHook(makeHookHandler(s), false);
      s.hookRearms++;
    }
  }
  injector.setKeyHookSwallow(shouldSwallow);
}

function startSession(role: Session['role'], peer: PeerInfo, perms: RcPermissions, sid: string): RcSessionInfo {
  endSession('revoked', false); // defensive: never two sessions
  const s: Session = {
    sid,
    role,
    peer,
    perms,
    keyHook: false,
    lastFrameAt: Date.now(),
    lastSeq: { key: 0, btn: 0, wheel: 0, mv: 0 },
    watchdog: null,
    clipboardTimer: null,
    lastClipboard: '',
    negotiated: negotiateCaps(undefined),
    capsSeen: false,
    hookEvents: 0,
    keyFramesIn: 0,
    keyDropped: 0,
    diagOn: false,
    diagItems: [],
    diagNext: 1,
    diagLastMove: 0,
    lastSwallow: false,
    captureLog: [],
    hookRearms: 0
  };
  injector.resetInjectStats();
  session = s;

  // The hook serves both roles: swallowing keys on the controller, and watching for the
  // Ctrl+Shift+Pause emergency stop on either side.
  s.keyHook = injector.startKeyHook(makeHookHandler(s), false);

  if (role === 'controlled') {
    s.watchdog = setInterval(() => {
      if (session === s && Date.now() - s.lastFrameAt > RC_TIMING.heartbeatTimeoutMs) endSession('heartbeat');
    }, 500);
    showControlIndicator(peer.name, () => endSession('user-exit'));
  }

  if (perms.clipboard) {
    s.lastClipboard = clipboard.readText(); // what was already there is never sent, only new copies
    s.clipboardTimer = setInterval(() => {
      if (session !== s) return;
      const text = clipboard.readText();
      if (text === s.lastClipboard) return;
      s.lastClipboard = text;
      if (text && text.length <= RC_TIMING.clipboardMaxChars) emit('rc:clipboard-local', { sid: s.sid, text });
    }, RC_TIMING.clipboardPollMs);
  }
  return sessionInfo(s);
}

/** Every way a session can end (revoke, disconnect, heartbeat, share stopped, quit...) goes
 * through here, so Input Reset can never be skipped. `notifyPeer` tells the renderer whether the
 * other side still has to be told (false when it is the one that ended it). */
function endSession(reason: RcEndReason, notifyPeer = true): void {
  const s = session;
  if (!s) return;
  session = null;
  if (s.watchdog) clearInterval(s.watchdog);
  if (s.clipboardTimer) clearInterval(s.clipboardTimer);
  if (s.role === 'controlled') {
    injector.resetInjectedInput();
    injector.releaseBackend();
  }
  injector.stopKeyHook();
  hideControlIndicator();
  captureActive = false;
  for (const listener of sessionEndListeners) listener();
  emit('rc:ended', { sid: s.sid, role: s.role, reason, notifyPeer });
}

// ---- incoming frames (controlled side) -----------------------------------------------------------

/** Remembers one input event's outcome for the diagnostics panel — only while diagnostics are on
 * (opt-in, in memory, dropped with the session, never logged or persisted). Mouse moves are sampled. */
function record(s: Session, item: Omit<DiagItem, 'id'>): void {
  if (!s.diagOn) return;
  if (item.kind === 'mv') {
    const now = Date.now();
    if (now - s.diagLastMove < 100) return;
    s.diagLastMove = now;
  }
  s.diagItems.push({ ...item, id: s.diagNext++ });
  if (s.diagItems.length > 200) s.diagItems.shift();
}

const outcomeOf = (result: string): DiagOutcome => (result === 'guard' ? 'guard' : result === 'fail' ? 'fail' : 'ok');

function acceptSeq(s: Session, kind: keyof Session['lastSeq'], seq: unknown): boolean {
  if (typeof seq !== 'number' || !Number.isFinite(seq) || seq <= s.lastSeq[kind]) return false; // replay / duplicate / stale
  s.lastSeq[kind] = seq;
  return true;
}

function handleInput(peerId: string, frame: ControlFrame): void {
  const s = session;
  if (!s || s.role !== 'controlled' || peerId !== s.peer.peerId) return;
  if (!frame || typeof frame !== 'object' || (frame as { sid?: unknown }).sid !== s.sid) return; // old/other session
  s.lastFrameAt = Date.now();
  switch (frame.t) {
    case 'hb':
      if (Array.isArray(frame.keys) && Array.isArray(frame.buttons)) injector.reconcilePressed(frame.keys, frame.buttons);
      break;
    case 'key': {
      s.keyFramesIn++;
      const base = { kind: 'key' as const, seq: frame.seq, value: frame.k, down: !!frame.down };
      if (!s.perms.keyboard) {
        s.keyDropped++;
        record(s, { ...base, outcome: 'perm' });
      } else if (!acceptSeq(s, 'key', frame.seq)) {
        s.keyDropped++;
        record(s, { ...base, outcome: 'seq' });
      } else {
        record(s, { ...base, outcome: outcomeOf(injector.injectKey(frame.k, !!frame.down)) });
      }
      break;
    }
    case 'btn': {
      const base = { kind: 'btn' as const, seq: frame.seq, value: frame.b, down: !!frame.down };
      if (!s.perms.mouse) record(s, { ...base, outcome: 'perm' });
      else if (!acceptSeq(s, 'btn', frame.seq)) record(s, { ...base, outcome: 'seq' });
      // Only buttons the controller's real mouse can produce (and the virtual one has) are injected.
      else if (frame.b >= s.negotiated.buttons) record(s, { ...base, outcome: 'perm' });
      else record(s, { ...base, outcome: outcomeOf(injector.injectButton(frame.b, !!frame.down)) });
      break;
    }
    case 'wheel': {
      const base = { kind: 'wheel' as const, seq: frame.seq, value: 0, down: false, dx: frame.dx, dy: frame.dy };
      if (!s.perms.mouse) record(s, { ...base, outcome: 'perm' });
      else if (!acceptSeq(s, 'wheel', frame.seq) || !Number.isFinite(frame.dx) || !Number.isFinite(frame.dy)) record(s, { ...base, outcome: 'seq' });
      else record(s, { ...base, outcome: outcomeOf(injector.injectWheel(s.negotiated.horizontalWheel ? frame.dx : 0, frame.dy)) });
      break;
    }
    case 'caps':
      // Once per session: the controller's real-hardware capabilities, validated here against what
      // this PC's virtual devices can reproduce. Anonymous facts only (common/deviceCaps.ts).
      if (!s.capsSeen) {
        s.capsSeen = true;
        s.negotiated = negotiateCaps(frame.caps);
        injector.configureBackend(s.negotiated);
        emit('rc:caps-result', { warnings: s.negotiated.warnings });
      }
      break;
  }
}

function handleMove(peerId: string, frame: MoveFrame): void {
  const s = session;
  if (!s || s.role !== 'controlled' || peerId !== s.peer.peerId || !shareDisplayId) return;
  if (!frame || frame.sid !== s.sid) return;
  const base = { kind: 'mv' as const, seq: frame.seq, value: 0, down: false, x: frame.x, y: frame.y };
  if (!s.perms.mouse) return record(s, { ...base, outcome: 'perm' });
  if (!acceptSeq(s, 'mv', frame.seq)) return record(s, { ...base, outcome: 'seq' });
  s.lastFrameAt = Date.now();
  record(s, { ...base, outcome: outcomeOf(injector.injectMoveNormalized(shareDisplayId, frame.x, frame.y)) });
}

// ---- IPC -------------------------------------------------------------------------------------------

// Whether this process runs elevated (administrator). `fltmc` only succeeds with an elevated token,
// which makes it a dependable, side-effect-free probe; the answer cannot change while we run.
let elevated: Promise<boolean> | null = null;
function isElevated(): Promise<boolean> {
  elevated ??= new Promise((resolve) => {
    if (process.platform !== 'win32') return resolve(false);
    execFile('fltmc', { windowsHide: true, timeout: 3000 }, (error) => resolve(!error));
  });
  return elevated;
}

ipcMain.handle('rc:state', async () => ({
  session: session ? sessionInfo(session) : null,
  available: injector.isInputAvailable(),
  status,
  sharingFullScreen: shareDisplayId !== null,
  elevated: await isElevated()
}));

ipcMain.handle('rc:set-status', (_event, next: unknown) => {
  if (!isStatus(next)) return;
  status = next;
  // A pending solicitation aimed at me is only valid while I am Online.
  if (status !== 'online' && pending?.direction === 'incoming') {
    const p = clearPending();
    if (p) emit('rc:pending-cancelled', { id: p.id });
  }
});

ipcMain.handle('rc:set-share', (_event, displayId: unknown) => {
  const next = typeof displayId === 'string' && displayId ? displayId : null;
  if (next === shareDisplayId) return;
  shareDisplayId = next;
  // Closing (or switching) the shared screen ends control at once (spec 13.3): the coordinate
  // mapping is tied to the display that was shared.
  if (session?.role === 'controlled') endSession('share-stopped');
  if (pending && ((pending.direction === 'incoming' && pending.kind === 'request') || (pending.direction === 'outgoing' && pending.kind === 'offer'))) {
    const p = clearPending();
    if (p) emit('rc:pending-cancelled', { id: p.id });
  }
});

/** Sender side: may I start a request/offer at all? Registers it as the one pending solicitation. */
ipcMain.handle('rc:begin-outgoing', (_event, kind: SolicitationKind, peer: unknown, rawPerms: unknown) => {
  const perms = normalizePerms(rawPerms);
  if ((kind !== 'request' && kind !== 'offer') || !isPeer(peer) || !perms) return { ok: false, reason: 'indisponivel' };
  if (session || pending) return { ok: false, reason: 'em-sessao' };
  if (kind === 'offer') {
    if (!injector.isInputAvailable()) return { ok: false, reason: 'indisponivel' };
    if (!shareDisplayId) return { ok: false, reason: 'sem-tela-inteira' };
  }
  const p = startPending('outgoing', kind, peer, perms, kind === 'offer' ? randomUUID() : null);
  return { ok: true, id: p.id, sid: p.sid };
});

/** Recipient side: the authoritative gate for a request/offer that arrived from a peer. `peer`
 * comes from the renderer's server-verified peer list, never from the frame itself. */
ipcMain.handle('rc:incoming', (_event, kind: SolicitationKind, peer: unknown, rawPerms: unknown, sid: unknown): RcIncomingVerdict => {
  const perms = normalizePerms(rawPerms);
  if ((kind !== 'request' && kind !== 'offer') || !isPeer(peer) || !perms) return { ok: false, reason: 'indisponivel' };
  if (session || pending) return { ok: false, reason: 'em-sessao' };
  if (status !== 'online') return { ok: false, reason: 'status' };
  if (kind === 'request') {
    if (!injector.isInputAvailable()) return { ok: false, reason: 'indisponivel' };
    if (!shareDisplayId) return { ok: false, reason: 'sem-tela-inteira' };
  } else if (typeof sid !== 'string' || !sid) {
    return { ok: false, reason: 'indisponivel' };
  }
  const block = blockStatus(loadBlocks()[peer.userId], Date.now());
  if (block.blocked) {
    return block.permanent ? { ok: false, reason: 'bloqueado' } : { ok: false, reason: 'cooldown', retryInMs: block.retryInMs };
  }
  const p = startPending('incoming', kind, peer, perms, kind === 'offer' ? (sid as string) : null);
  return { ok: true, id: p.id };
});

/** Recipient's answer. A refusal feeds the cooldown (per sender userId); accepting starts the session. */
ipcMain.handle('rc:respond', async (_event, id: string, accept: boolean) => {
  const p = pending;
  if (!p || p.id !== id || p.direction !== 'incoming') return { ok: false };
  clearPending();
  if (!accept) {
    const all = loadBlocks();
    all[p.peer.userId] = { ...recordRefusal(all[p.peer.userId], Date.now()), displayName: p.peer.name };
    saveBlocks();
    return { ok: true };
  }
  if (p.kind === 'request') {
    // I am the controlled PC: the session id is mine to mint.
    if (!shareDisplayId || !injector.isInputAvailable()) return { ok: false };
    await injector.prepareBackend(); // Virtual HID service when present, SendInput otherwise
    const info = startSession('controlled', p.peer, p.perms, randomUUID());
    return { ok: true, session: info };
  }
  return { ok: true, session: startSession('controller', p.peer, p.perms, p.sid as string) };
});

/** Sender's side of the outcome (the `res` frame that came back over the data channel). */
ipcMain.handle('rc:outgoing-result', async (_event, id: string, result: 'accepted' | 'refused' | 'rejected' | 'cancelled', sid?: string) => {
  const p = pending;
  if (!p || p.id !== id || p.direction !== 'outgoing') return { ok: false };
  clearPending();
  if (result !== 'accepted') return { ok: true };
  if (p.kind === 'request') {
    if (typeof sid !== 'string' || !sid) return { ok: false };
    return { ok: true, session: startSession('controller', p.peer, p.perms, sid) };
  }
  if (!shareDisplayId || !injector.isInputAvailable()) return { ok: false };
  await injector.prepareBackend();
  return { ok: true, session: startSession('controlled', p.peer, p.perms, p.sid as string) };
});

/** Drops the pending solicitation (sender cancelled, or the peer's `cancel` frame arrived). */
ipcMain.handle('rc:cancel-pending', (_event, id: string) => {
  if (pending?.id === id) clearPending();
});

ipcMain.handle('rc:end', (_event, reason: RcEndReason) => endSession(reason));
ipcMain.handle('rc:peer-ended', (_event, sid: string) => {
  if (session?.sid === sid) endSession('revoked', false);
});

/** Turns the per-event diagnostics on/off for this session (off = nothing is recorded, ring cleared). */
ipcMain.handle('rc:diag-enable', (_event, on: boolean) => {
  if (!session) return;
  session.diagOn = !!on;
  if (!on) session.diagItems = [];
});

/** Events recorded after `afterId` (controlled side): what actually arrived and what Windows did. */
ipcMain.handle('rc:diag-items', (_event, afterId: number): DiagItem[] => {
  if (!session || !session.diagOn) return [];
  return session.diagItems.filter((item) => item.id > afterId).slice(-100);
});

/** Where a typed key currently stops (counters only, never contents) — see RcDiag. */
ipcMain.handle('rc:diag', async (): Promise<RcDiag | null> => {
  const s = session;
  if (!s) return null;
  return {
    role: s.role,
    keyHook: s.keyHook,
    swallowing: s.role === 'controller' && s.perms.keyboard && captureActive && !!mainWindow?.isFocused(),
    captureActive,
    windowFocused: !!mainWindow?.isFocused(),
    captureWhy: captureWhy(s),
    captureLog: s.captureLog,
    hookRearms: s.hookRearms,
    hookEvents: s.hookEvents,
    keyFramesIn: s.keyFramesIn,
    keyDropped: s.keyDropped,
    injected: injector.injectStats.injected,
    injectFailed: injector.injectStats.failed,
    elevated: await isElevated()
  };
});

/** This PC's own keyboard/mouse capabilities, for the controller to send at session start. */
ipcMain.handle('rc:local-caps', () => injector.readLocalCapabilities());

ipcMain.handle('rc:capture', (_event, active: boolean) => {
  captureActive = !!active;
  applySwallow();
});

ipcMain.on('rc:input', (_event, peerId: string, frame: ControlFrame) => handleInput(peerId, frame));
ipcMain.on('rc:move', (_event, peerId: string, frame: MoveFrame) => handleMove(peerId, frame));

/** Clipboard text from the peer (either role) — only with the clipboard permission of this session. */
ipcMain.on('rc:clipboard-remote', (_event, peerId: string, sid: string, text: string) => {
  const s = session;
  if (!s || !s.perms.clipboard || peerId !== s.peer.peerId || sid !== s.sid) return;
  if (typeof text !== 'string' || text.length > RC_TIMING.clipboardMaxChars) return;
  s.lastClipboard = text; // so the poller doesn't echo it straight back
  clipboard.writeText(text);
});

ipcMain.handle('rc:list-blocked', (): RcBlockedUser[] => {
  const now = Date.now();
  return Object.entries(loadBlocks())
    .map(([userId, record]) => {
      const status = blockStatus(record, now);
      return {
        userId,
        displayName: record.displayName,
        permanent: status.blocked && status.permanent,
        retryInMs: status.blocked && !status.permanent ? status.retryInMs : 0,
        refusals: record.refusals.length,
        blocked: status.blocked
      };
    })
    .filter((entry) => entry.blocked)
    .map(({ blocked: _blocked, ...entry }) => entry);
});

ipcMain.handle('rc:unblock', (_event, userId: string) => {
  const all = loadBlocks();
  if (!(userId in all)) return false;
  delete all[userId]; // also clears the refusal history: the counter starts from zero again
  saveBlocks();
  return true;
});

// ---- wiring --------------------------------------------------------------------------------------

export function attachRemoteControlWindow(window: BrowserWindow): void {
  mainWindow = window;
  window.on('focus', applySwallow);
  window.on('blur', applySwallow);
  // Renderer crashed or was reloaded: nobody is left to heartbeat or to stop the session — let go now.
  window.webContents.on('render-process-gone', () => endSession('error'));
  window.webContents.on('did-start-navigation', (_event, _url, _isInPlace, isMainFrame) => {
    if (isMainFrame) endSession('error', false);
  });
  window.on('closed', () => {
    endSession('user-exit', false);
    if (mainWindow === window) mainWindow = null;
  });
}

// The Virtual HID service dropping mid-session means input silently stops: end the session.
injector.setBackendLostHandler(() => endSession('error'));

app.on('before-quit', () => endSession('user-exit', false));
app.whenReady().then(() => {
  powerMonitor.on('suspend', () => endSession('error'));
  powerMonitor.on('lock-screen', () => endSession('error'));
});
